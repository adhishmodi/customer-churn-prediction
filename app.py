def parse_optional_number(value: str, field_name: str) -> float:
    """Parse a numeric form value; blank means missing for the fitted imputer."""
    if not value.strip():
        return float("nan")
    try:
        number = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field_name} must be a number or left blank.") from exc
    if number < 0:
        raise ValueError(f"{field_name} cannot be negative.")
    return number


def validate_batch_frame(
    frame: pd.DataFrame, max_rows: int = MAX_BATCH_ROWS
) -> pd.DataFrame:
    """Validate the uploaded CSV against the exact inference feature contract."""
    if not isinstance(frame, pd.DataFrame):
        raise TypeError("The uploaded CSV must be read as a pandas DataFrame.")
    if len(frame) > max_rows:
        raise ValueError(f"Batch is limited to {max_rows:,} customer rows.")
    normalized, is_single = prepare_inference_features(frame)
    if is_single:
        raise RuntimeError("Batch validation unexpectedly produced a single row.")
    return normalized


def predict_batch(
    frame: pd.DataFrame, artifact: dict[str, Any] | str | Path
) -> pd.DataFrame:
    """Validate and predict a batch while preserving customer row order."""
    features = validate_batch_frame(frame)
    predictions = predict_customer(features, artifact)
    if not isinstance(predictions, pd.DataFrame):
        raise RuntimeError("Batch inference did not return a DataFrame.")
    if len(predictions) != len(features) or not predictions.index.equals(features.index):
        raise RuntimeError("Batch inference changed the row count or row order.")
    return pd.concat(
        [features.reset_index(drop=True), predictions.reset_index(drop=True)], axis=1
    )


def make_download_csv(frame: pd.DataFrame) -> bytes:
    """Serialize results while neutralizing spreadsheet-formula-like text cells."""
    safe = frame.copy()
    for column in safe.select_dtypes(include=["object", "string"]).columns:
        safe[column] = safe[column].map(
            lambda value: (
                "'" + value
                if isinstance(value, str) and value.startswith(("=", "+", "-", "@"))
                else value
            )
        )
    return safe.to_csv(index=False).encode("utf-8")


def _render_single_customer(st: Any, artifact: dict[str, Any]) -> None:
    st.subheader("Single-customer prediction")
    st.caption("Enter the customer's 19 model features. Leave numeric fields blank when unknown.")
    values: dict[str, Any] = {}

    with st.form("single_customer_form"):
        numeric_columns = st.columns(3)
        numeric_features = ("tenure", "MonthlyCharges", "TotalCharges")
        numeric_labels = ("Tenure (months)", "Monthly charges", "Total charges")
        for index, (feature, label) in enumerate(zip(numeric_features, numeric_labels)):
            with numeric_columns[index]:
                values[feature] = st.text_input(
                    label,
                    value=str(DEFAULT_CUSTOMER[feature]),
                    help="Enter a non-negative number, or leave blank if unknown.",
                )

        st.markdown("**Services and customer details**")
        categorical_columns = st.columns(3)
        for index, feature in enumerate(CATEGORICAL_FEATURES):
            with categorical_columns[index % 3]:
                options = CATEGORY_OPTIONS[feature]
                selected = st.selectbox(
                    feature,
                    options + [CUSTOM_OPTION],
                    index=options.index(DEFAULT_CUSTOMER[feature]),
                    key=f"single_{feature}",
                )
                if selected == CUSTOM_OPTION:
                    values[feature] = st.text_input(
                        f"Custom {feature}",
                        key=f"custom_{feature}",
                        placeholder="Enter category value",
                    )
                else:
                    values[feature] = selected

        submitted = st.form_submit_button("Predict churn", type="primary")

    if submitted:
        try:
            customer = dict(values)
            for column in ("tenure", "MonthlyCharges", "TotalCharges"):
                customer[column] = parse_optional_number(customer[column], column)
            missing_custom = [
                feature for feature in CATEGORICAL_FEATURES
                if not isinstance(customer[feature], str) or not customer[feature].strip()
            ]
            if missing_custom:
                raise ValueError(f"Enter a value for: {', '.join(missing_custom)}.")
            result = predict_customer(customer, artifact)
            probability = float(result["churn_probability"])
            st.divider()
            st.metric("Estimated churn probability", f"{probability:.1%}")
            st.metric("Predicted churn", result["predicted_churn"])
            st.caption(
                f"Decision threshold: {float(result['decision_threshold']):.4f}. "
                "The label is Yes when the calibrated probability meets or exceeds this threshold."
            )
        except (ValueError, TypeError, KeyError) as exc:
            st.error(str(exc))
        except Exception:
            st.error("Prediction failed. Check the model artifact and input values, then try again.")


def _render_batch_prediction(st: Any, artifact: dict[str, Any]) -> None:
    st.subheader("Batch CSV prediction")
    st.write("Upload a CSV containing exactly the 19 model features. Do not include customerID or Churn.")
    uploaded = st.file_uploader("Customer CSV", type=["csv"], accept_multiple_files=False)

    if uploaded is None:
        st.info("Your uploaded data is processed in memory for this session and is not saved by the app.")
        return

    try:
        payload = uploaded.getvalue()
        if len(payload) > MAX_UPLOAD_BYTES:
            raise ValueError(f"CSV must be no larger than {MAX_UPLOAD_BYTES // (1024 * 1024)} MB.")
        frame = pd.read_csv(BytesIO(payload))
        features = validate_batch_frame(frame)
        results = predict_batch(features, artifact)
        st.success(f"Generated predictions for {len(results):,} customers.")
        st.dataframe(results.head(100), use_container_width=True)
        st.download_button(
            "Download predictions CSV",
            data=make_download_csv(results),
            file_name="customer_churn_predictions.csv",
            mime="text/csv",
        )
    except (ValueError, TypeError, pd.errors.ParserError, UnicodeDecodeError) as exc:
        st.error(f"Could not process this CSV: {exc}")
    except Exception:
        st.error("Batch prediction failed. Verify that the trusted Phase 7A artifact is compatible.")


def main() -> None:
    """Render the Streamlit app; Streamlit remains an optional dependency."""
    try:
        import streamlit as st
    except ImportError as exc:
        raise SystemExit(
            "Streamlit is optional. Install it with: pip install 'streamlit>=1.30'"
        ) from exc

    st.set_page_config(page_title="Customer Churn Predictor", page_icon="📊", layout="wide")
    st.title("Customer Churn Predictor")
    st.caption("Phase 7B · Balanced XGBoost with sigmoid calibration")
    st.warning(
        "Predictions are decision-support estimates, not guarantees. "
        "Do not enter sensitive personal information."
    )

    artifact_path = Path(DEFAULT_ARTIFACT_PATH)
    if not artifact_path.is_file():
        st.error(
            f"Model artifact not found at {artifact_path}. "
            "Generate it by running Notebook 12 in Colab, then place the trusted "
            "artifact at this path in the app environment."
        )
        st.stop()

    @st.cache_resource(show_spinner="Loading the Phase 7A model...")
    def cached_artifact(path: str) -> dict[str, Any]:
        return load_model_artifact(path)

    try:
        artifact = cached_artifact(str(artifact_path))
    except Exception:
        st.error(
            "The model artifact could not be loaded or failed compatibility checks. "
            "Use the trusted artifact generated by Notebook 12."
        )
        st.stop()

    st.sidebar.header("Model information")
    st.sidebar.write(f"Calibration: {artifact['calibration_method']}")
    st.sidebar.write(f"Decision threshold: {float(artifact['threshold']):.4f}")
    st.sidebar.caption("Model and threshold are loaded from the Phase 7A artifact.")

    single_tab, batch_tab = st.tabs(["Single customer", "Batch CSV"])
    with single_tab:
        _render_single_customer(st, artifact)
    with batch_tab:
        _render_batch_prediction(st, artifact)


if __name__ == "__main__":
    main()
